// 13.9: writes public/sitemap.xml (home, listing, deals, help, every category, every active product) and
// public/robots.txt (which points at it) from the live API. Run it against a running backend:
//   VITE_SITE_URL=https://shop.example npm run sitemap
// A static site cannot ask the API per request, so the sitemap is regenerated when the catalog changes
// (in CI before `npm run build`, or on a schedule). If the API is unreachable the existing files are kept.
import { readFileSync, writeFileSync, existsSync } from "node:fs"

function envFile() {
  try {
    return Object.fromEntries(
      readFileSync(new URL("../.env.local", import.meta.url), "utf8")
        .split("\n")
        .filter((l) => l.includes("=") && !l.startsWith("#"))
        .map((l) => l.split(/=(.*)/s).slice(0, 2))
    )
  } catch {
    return {}
  }
}
const env = { ...envFile(), ...process.env }
const API = (env.VITE_API_URL ?? "http://localhost:4000/api/v1").replace(
  /\/$/,
  ""
)
const SITE = (env.VITE_SITE_URL ?? "http://localhost:5173").replace(/\/$/, "")

const get = async (path) => {
  const res = await fetch(`${API}${path}`)
  if (!res.ok) throw new Error(`${path} -> ${res.status}`)
  return res.json()
}
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;")

try {
  const tree = (await get("/categories")).data
  const slugs = []
  const walk = (nodes) =>
    nodes.forEach((n) => (slugs.push(n.slug), walk(n.children ?? [])))
  walk(tree)

  const products = []
  for (let page = 1; ; page++) {
    const body = await get(`/products?page=${page}&limit=60&sort=newest`)
    products.push(
      ...body.data.map((p) => ({ slug: p.slug, lastmod: p.updatedAt }))
    )
    if (!body.meta.hasNext) break
  }

  const today = new Date().toISOString().slice(0, 10)
  const urls = [
    { loc: "/", changefreq: "daily", priority: "1.0", lastmod: today },
    { loc: "/products", changefreq: "daily", priority: "0.8", lastmod: today },
    { loc: "/deals", changefreq: "hourly", priority: "0.7", lastmod: today },
    { loc: "/help", changefreq: "monthly", priority: "0.3", lastmod: today },
    ...slugs.map((s) => ({
      loc: `/c/${s}`,
      changefreq: "daily",
      priority: "0.7",
      lastmod: today,
    })),
    ...products.map((p) => ({
      loc: `/p/${p.slug}`,
      changefreq: "weekly",
      priority: "0.6",
      lastmod: p.lastmod.slice(0, 10),
    })),
  ]
  const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls
    .map(
      (u) =>
        `  <url><loc>${esc(SITE + u.loc)}</loc><lastmod>${u.lastmod}</lastmod><changefreq>${u.changefreq}</changefreq><priority>${u.priority}</priority></url>`
    )
    .join("\n")}\n</urlset>\n`
  writeFileSync(new URL("../public/sitemap.xml", import.meta.url), xml)

  const robots = `# robots.txt (generated by scripts/generate-sitemap.mjs)
User-agent: *
Allow: /
# Private or transactional: nothing to index. (These pages also send <meta name="robots" content="noindex">.)
Disallow: /cart
Disallow: /checkout
Disallow: /account
Disallow: /orders
Disallow: /wishlist
Disallow: /seller
Disallow: /login
Disallow: /register
Disallow: /forgot-password
Disallow: /reset-password
Disallow: /verify-email
Disallow: /auth/
Disallow: /offline
Disallow: /dev
# Internal search results are thin duplicates of the listing.
Disallow: /*?search=

Sitemap: ${SITE}/sitemap.xml
`
  writeFileSync(new URL("../public/robots.txt", import.meta.url), robots)
  console.log(
    `sitemap.xml: ${urls.length} URLs (${products.length} products, ${slugs.length} categories) for ${SITE}`
  )
} catch (err) {
  console.warn(
    `sitemap NOT updated (${err.message}); keeping the existing files`
  )
  if (!existsSync(new URL("../public/sitemap.xml", import.meta.url)))
    process.exitCode = 1
}
